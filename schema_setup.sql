-- 1. Facility Settings Table
CREATE TABLE IF NOT EXISTS public.settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility_name TEXT DEFAULT 'Naples Surgery Center',
    facility_address TEXT DEFAULT '123 Medical Blvd',
    facility_city TEXT DEFAULT 'Naples',
    facility_state TEXT DEFAULT 'FL',
    facility_zip TEXT DEFAULT '34102',
    facility_phone TEXT DEFAULT '(555) 123-4567',
    tax_id TEXT DEFAULT '59-1234567',
    npi TEXT DEFAULT '1234567890',
    apply_medicare_mppr BOOLEAN DEFAULT false,
    gemini_api_key TEXT,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Insert initial settings row if not exists
INSERT INTO public.settings (facility_name)
SELECT 'Naples Surgery Center'
WHERE NOT EXISTS (SELECT 1 FROM public.settings);

-- 2. Surgeons Table
CREATE TABLE IF NOT EXISTS public.surgeons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname TEXT NOT NULL,
    lastname TEXT NOT NULL,
    specialty TEXT,
    license_number TEXT,
    email TEXT,
    phone TEXT,
    years_of_experience NUMERIC DEFAULT 0,
    is_cosmetic_surgeon BOOLEAN DEFAULT false,
    password TEXT,
    block_templates JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Patients Table
CREATE TABLE IF NOT EXISTS public.patients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    dob DATE,
    mrn TEXT,
    gender TEXT,
    phone TEXT,
    email TEXT,
    address TEXT,
    insurance_provider TEXT,
    insurance_policy_number TEXT,
    insurance_group_number TEXT,
    insurance_type TEXT,
    subscriber_name TEXT,
    subscriber_relationship TEXT,
    insurance_effective_date DATE,
    insurance_expiration_date DATE,
    copay_amount NUMERIC(10, 2) DEFAULT 0.00,
    deductible_amount NUMERIC(10, 2) DEFAULT 0.00,
    secondary_insurance_provider TEXT,
    secondary_insurance_policy_number TEXT,
    secondary_insurance_group_number TEXT,
    emergency_contact_name TEXT,
    emergency_contact_phone TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. CPT Codes Table
CREATE TABLE IF NOT EXISTS public.cpt_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL,
    description TEXT,
    short_descriptor TEXT,
    long_descriptor TEXT,
    category TEXT,
    procedure_group TEXT,
    procedure_indicator TEXT,
    payment_indicator TEXT,
    body_part TEXT,
    reimbursement NUMERIC(12, 2) DEFAULT 0.00,
    cost NUMERIC(12, 2) DEFAULT 0.00,
    gross_charge NUMERIC(12, 2) DEFAULT 0.00,
    average_duration NUMERIC(10, 2) DEFAULT 0.00,
    turnover_time NUMERIC(10, 2) DEFAULT 0.00,
    effective_date DATE,
    termination_date DATE,
    version_year TEXT,
    last_updated_from_source TIMESTAMPTZ,
    original_filename TEXT,
    details TEXT,
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Index for fast CPT lookups
CREATE INDEX IF NOT EXISTS idx_cpt_codes_code ON public.cpt_codes(code);

-- 5. Surgeries Table
CREATE TABLE IF NOT EXISTS public.surgeries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT REFERENCES public.patients(id) ON DELETE SET NULL,
    surgeon_id BIGINT REFERENCES public.surgeons(id) ON DELETE SET NULL,
    doctor_name TEXT,
    date DATE,
    start_time TIME,
    duration_minutes INTEGER DEFAULT 60,
    cpt_codes TEXT,
    status TEXT DEFAULT 'Scheduled',
    notes TEXT,
    actual_room_cost NUMERIC(12, 2) DEFAULT 0.00,
    actual_labor_cost NUMERIC(12, 2) DEFAULT 0.00,
    expected_reimbursement NUMERIC(12, 2) DEFAULT 0.00,
    supplies_cost NUMERIC(12, 2) DEFAULT 0.00,
    implants_cost NUMERIC(12, 2) DEFAULT 0.00,
    medications_cost NUMERIC(12, 2) DEFAULT 0.00,
    financial_snapshot_date TIMESTAMPTZ,
    calculation_version TEXT,
    turnover_time INTEGER DEFAULT 15,
    or_room INTEGER DEFAULT 1,
    actual_start_time TEXT,
    actual_end_time TEXT,
    actual_duration_minutes INTEGER,
    write_off NUMERIC(12, 2) DEFAULT 0.00,
    is_probono BOOLEAN DEFAULT false,
    cpt_expenses JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. OR Block Schedule Table
CREATE TABLE IF NOT EXISTS public.or_block_schedule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_name TEXT,
    day_of_week TEXT,
    week_of_month TEXT,
    provider_name TEXT,
    start_time TEXT,
    end_time TEXT,
    date DATE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. OT Extra Costs Table
CREATE TABLE IF NOT EXISTS public.ot_extra_cost (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    cpt_codes TEXT NOT NULL,
    supply_cost NUMERIC(10, 2) DEFAULT 0.00,
    implant_cost NUMERIC(10, 2) DEFAULT 0.00,
    labour_cost NUMERIC(10, 2) DEFAULT 0.00,
    or_room_cost NUMERIC(10, 2) DEFAULT 0.00,
    medication_cost NUMERIC(10, 2) DEFAULT 0.00,
    tray_cost NUMERIC(10, 2) DEFAULT 0.00,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. Clinical Staff Table
CREATE TABLE IF NOT EXISTS public.staff (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname TEXT NOT NULL,
    lastname TEXT NOT NULL,
    role TEXT,
    department TEXT,
    specialty TEXT,
    license_id TEXT,
    license_number TEXT,
    phone TEXT,
    email TEXT,
    hourly_rate NUMERIC(10, 2) DEFAULT 0.00,
    monthly_salary NUMERIC(10, 2) DEFAULT 0.00,
    benefits NUMERIC(10, 2) DEFAULT 0.00,
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. Chatbot Questions Table
CREATE TABLE IF NOT EXISTS public.chatbot_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question TEXT NOT NULL,
    category TEXT,
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 10. Users Table (Administrators / Management Staff)
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'admin',
    avatar TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Seed initial admin user if not exists
INSERT INTO public.users (name, email, password, role)
SELECT 'Admin Director', 'admin@asc.com', 'admin123', 'admin'
WHERE NOT EXISTS (SELECT 1 FROM public.users WHERE email = 'admin@asc.com');

