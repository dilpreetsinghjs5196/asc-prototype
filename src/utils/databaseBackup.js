/**
 * Fetches all rows from a table using pagination to bypass Supabase's default limit
 */
async function fetchAllTableRows(tableName, onProgress) {
  let allRows = [];
  let page = 0;
  const pageSize = 1000;
  let hasMore = true;

  while (hasMore) {
    const { data, error } = await supabase
      .from(tableName)
      .select('*')
      .range(page * pageSize, (page + 1) * pageSize - 1);

    if (error) {
      console.warn(`Error fetching table ${tableName}:`, error);
      throw error;
    }

    if (data && data.length > 0) {
      allRows = allRows.concat(data);
      if (onProgress) {
        onProgress(allRows.length);
      }
      if (data.length < pageSize) {
        hasMore = false;
      } else {
        page++;
      }
    } else {
      hasMore = false;
    }
  }

  return allRows;
}

/**
 * Generates SQL batch insert statements for rows
 */
function generateTableInserts(tableName, rows) {
  if (!rows || rows.length === 0) return '';
  const cols = Object.keys(rows[0]);
  const quotedCols = cols.map(c => `"${c}"`).join(', ');

  const BATCH_SIZE = 50;
  let sql = '';

  for (let i = 0; i < rows.length; i += BATCH_SIZE) {
    const batch = rows.slice(i, i + BATCH_SIZE);
    const valueTuples = batch.map(row => {
      const vals = cols.map(c => escapeSqlValue(row[c]));
      return `(${vals.join(', ')})`;
    });

    sql += `INSERT INTO public.${tableName} (${quotedCols}) VALUES\n  ${valueTuples.join(',\n  ')};\n\n`;
  }

  return sql;
}

/**
 * Downloads a complete PostgreSQL .sql database backup file
 * @param {Function} onProgress Callback receiving progress status
 * @returns {Promise<Object>} Backup metadata
 */
export async function downloadDatabaseBackup(onProgress) {
  const timestamp = new Date();
  const dateStr = timestamp.toISOString().replace(/T/, '_').replace(/:/g, '-').replace(/\..+/, '');
  const fileName = `asc_database_backup_${dateStr}.sql`;

  const tableCounts = {};
  let totalRecords = 0;

  let sql = `-- ====================================================================\n`;
  sql += `-- ASC Profitability Command Center - Full Database Backup (.sql)\n`;
  sql += `-- Generated: ${timestamp.toISOString()}\n`;
  sql += `-- PostgreSQL 14+ & Supabase Compatible SQL Dump\n`;
  sql += `-- ====================================================================\n\n`;
  sql += `SET statement_timeout = 0;\n`;
  sql += `SET lock_timeout = 0;\n`;
  sql += `SET client_encoding = 'UTF8';\n`;
  sql += `SET standard_conforming_strings = on;\n`;
  sql += `SET check_function_bodies = false;\n`;
  sql += `SET xmloption = content;\n`;
  sql += `SET client_min_messages = warning;\n`;
  sql += `SET row_security = off;\n\n`;
  sql += `BEGIN;\n\n`;

  for (let idx = 0; idx < BACKUP_TABLES.length; idx++) {
    const { name: tableName, label } = BACKUP_TABLES[idx];

    if (onProgress) {
      onProgress({
        phase: 'fetching',
        currentTable: tableName,
        label,
        tableIndex: idx + 1,
        totalTables: BACKUP_TABLES.length,
        totalRecordsSoFar: totalRecords
      });
    }

    try {
      const rows = await fetchAllTableRows(tableName, (count) => {
        if (onProgress) {
          onProgress({
            phase: 'fetching',
            currentTable: tableName,
            label,
            tableIndex: idx + 1,
            totalTables: BACKUP_TABLES.length,
            rowsFetched: count,
            totalRecordsSoFar: totalRecords + count
          });
        }
      });

      tableCounts[tableName] = rows.length;
      totalRecords += rows.length;

      sql += `-- --------------------------------------------------------------------\n`;
      sql += `-- Table: public.${tableName} (${rows.length} rows)\n`;
      sql += `-- --------------------------------------------------------------------\n`;

      if (TABLE_SCHEMAS[tableName]) {
        sql += `${TABLE_SCHEMAS[tableName]}\n\n`;
      }

      if (rows.length > 0) {
        sql += generateTableInserts(tableName, rows);
      }
    } catch (err) {
      console.error(`Error backing up table ${tableName}:`, err);
      sql += `-- Warning: Could not export table ${tableName}: ${err.message}\n\n`;
      tableCounts[tableName] = 0;
    }
  }

  if (onProgress) {
    onProgress({
      phase: 'finalizing',
      currentTable: 'Sequences & Finalizing',
      label: 'Sequences & Constraints',
      tableIndex: BACKUP_TABLES.length,
      totalTables: BACKUP_TABLES.length,
      totalRecordsSoFar: totalRecords
    });
  }

  // Synchronize Primary Key Sequences
  sql += `-- --------------------------------------------------------------------\n`;
  sql += `-- Synchronize Primary Key Auto-Increment Sequences\n`;
  sql += `-- --------------------------------------------------------------------\n`;
  for (const { name: tableName } of BACKUP_TABLES) {
    if (tableName !== 'ot_extra_cost') {
      sql += `SELECT setval(pg_get_serial_sequence('public.${tableName}', 'id'), COALESCE((SELECT MAX(id) FROM public.${tableName}), 1), true);\n`;
    }
  }

  sql += `\nCOMMIT;\n\n`;
  sql += `-- ====================================================================\n`;
  sql += `-- Backup completed successfully. Total records exported: ${totalRecords}\n`;
  sql += `-- ====================================================================\n`;

  // Trigger file download
  const blob = new Blob([sql], { type: 'application/sql;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = fileName;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);

  const fileSizeMB = (blob.size / (1024 * 1024)).toFixed(2);

  return {
    success: true,
    fileName,
    fileSizeMB,
    totalRecords,
    tableCounts
  };
}
